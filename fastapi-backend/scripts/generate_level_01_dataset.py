EMPTY_ELEMENTS = {
    "slabs": [],
    "columns": [],
    "beams": [],
    "doors": [],
    "windows": [],
    "roofs": [],
    "stairs": [],
    "spaces": [],
}


def make_record(
    index: int,
    prompt: str,
    *,
    project_name: str,
    site_name: str,
    site_location: str,
    building_name: str,
    storey_name: str,
    storey_elevation: float,
    storey_height: float,
    wall_name: str,
    wall_material: str,
    start: list[float],
    end: list[float],
    height: float,
    thickness: float,
    latitude: float | None = None,
    longitude: float | None = None,
) -> dict:
    idx = f"{index:03d}"
    storey_id = f"storey-{idx}"
    wall_id = f"wall-{idx}"

    return {
        "input": prompt,
        "output": {
            "project": {
                "id": f"proj-{idx}",
                "name": project_name,
                "description": f"Level 1 single-wall example {index}",
            },
            "site": {
                "id": f"site-{idx}",
                "name": site_name,
                "location": site_location,
                "latitude": latitude,
                "longitude": longitude,
            },
            "building": {
                "id": f"bld-{idx}",
                "name": building_name,
                "storeys": [storey_id],
            },
            "storeys": [
                {
                    "id": storey_id,
                    "name": storey_name,
                    "elevation": storey_elevation,
                    "height": storey_height,
                }
            ],
            "elements": {
                "walls": [
                    {
                        "id": wall_id,
                        "name": wall_name,
                        "storey": storey_id,
                        "material": wall_material,
                        "geometry": {
                            "start": start,
                            "end": end,
                            "height": height,
                            "thickness": thickness,
                        },
                    }
                ],
                **EMPTY_ELEMENTS,
            },
            "materials": [],
            "relationships": [],
            "metadata": {
                "units": "meters",
                "coordinate_system": "right_handed_z_up",
                "schema_version": "1.0",
                "note": "Level 1 single-wall training example.",
            },
        },
    }


